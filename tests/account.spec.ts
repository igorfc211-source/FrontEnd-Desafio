import { expect, test } from '@playwright/test'
import { action, collectorEmail, fixturePassword, fixtureTitle, login, logout, openCheckout, visit } from './support'

test('validates registration, handles conflict and creates a recoverable session', async ({ page }) => {
  await visit(page, '/register')
  const submit = page.getByRole('button', { name: /^criar conta$/i })
  await submit.click()
  await expect(page.getByLabel(/^nome(?: completo)?$/i)).toBeFocused()

  await page.getByLabel(/^nome(?: completo)?$/i).fill('Pessoa de Teste')
  await page.getByLabel(/^e-mail$/i).fill(collectorEmail)
  await page.getByLabel(/^senha$/i).fill(fixturePassword)
  await page.getByLabel(/confirm.*senha/i).fill(fixturePassword)
  await submit.click()
  await expect(page.getByText(/e-mail.*(?:já|uso|cadastrad)/i).first()).toBeVisible()
  await expect(page.getByLabel(/^e-mail$/i)).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByLabel(/^e-mail$/i)).toHaveAccessibleDescription(/e-mail|endereço/i)
  await page.getByLabel(/^e-mail$/i).fill('new-collector@example.com')
  await submit.click()
  await expect(page).not.toHaveURL(/\/register/)
  await page.goto('/profile')
  await expect(page.getByLabel(/^nome(?: completo)?$/i)).toHaveValue('Pessoa de Teste')
  await page.reload()
  await expect(page.getByLabel(/^nome(?: completo)?$/i)).toHaveValue('Pessoa de Teste')
})

test('resumes the checkout after session expiration', async ({ page }) => {
  await visit(page)
  await openCheckout(page)
  await page.getByLabel(/^nome completo$/i).fill('Alex Durante Checkout')
  await action(page, { type: 'expire-session' })
  await page.getByRole('button', { name: /conectar carteira/i }).click()
  await expect(page).toHaveURL(/\/login/)
  expect(new URL(page.url()).searchParams.get('redirect')).toBe('/checkout')
  await login(page)
  await expect(page).toHaveURL(/\/checkout/)
  await expect(page.getByLabel(/^nome completo$/i)).toHaveValue('Alex Durante Checkout')
  await expect(page.getByText(fixtureTitle, { exact: true }).first()).toBeVisible()
})

test('updates profile, avatar and password, and handles incorrect current password', async ({ page }) => {
  await visit(page, '/profile')
  await login(page)
  const name = page.getByLabel(/^nome(?: completo)?$/i)
  await name.fill('Alex Colecionador')
  await page.getByLabel(/sobre você/i).fill('Perfil atualizado no teste.')
  await page.locator('input[type="file"]').setInputFiles({
    name: 'avatar.png',
    mimeType: 'image/png',
    buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aH24AAAAASUVORK5CYII=', 'base64'),
  })
  await page.getByRole('button', { name: /salvar (?:alterações|perfil|dados)/i }).click()
  await expect(page.getByText('Perfil atualizado.')).toBeVisible()
  await page.reload()
  await expect(name).toHaveValue('Alex Colecionador')
  await expect(page.getByLabel(/sobre você/i)).toHaveValue('Perfil atualizado no teste.')
  await expect(page.getByRole('img', { name: 'Avatar do colecionador' })).toBeVisible()

  const currentPassword = page.getByLabel(/^senha atual$/i)
  const newPassword = 'NewGaleria123!'
  await currentPassword.fill('incorrect-password')
  await page.getByLabel(/^nova senha$/i).fill(newPassword)
  await page.getByLabel(/confirm.*senha/i).fill(newPassword)
  const changePassword = page.getByRole('button', { name: /alterar senha|salvar senha/i })
  await changePassword.click()
  await expect(page.getByText(/senha atual.*(incorreta|inválida)/i).first()).toBeVisible()
  await currentPassword.fill(fixturePassword)
  await changePassword.click()
  await expect(page.getByText(/senha.*(atualizada|alterada)/i).first()).toBeVisible()
  await logout(page)
  await page.goto('/profile')
  await login(page, collectorEmail, newPassword)
  await expect(name).toHaveValue('Alex Colecionador')
})

test('validates and saves a wallet, makes it primary and edits it', async ({ page }) => {
  await visit(page, '/wallets')
  await login(page)
  await page.getByRole('button', { name: /adicionar carteira|nova carteira/i }).click()
  const name = page.getByLabel(/nome da carteira/i)
  const address = page.getByLabel(/endereço/i)
  await name.fill('Carteira de teste')
  await address.fill('0xerrado')
  const save = page.getByRole('button', { name: /salvar carteira|cadastrar carteira/i })
  await save.click()
  await expect(address).toHaveAttribute('aria-invalid', 'true')
  await address.fill(`0x${'f1'.repeat(20)}`)
  await page.getByRole('checkbox', { name: /definir como carteira principal/i }).check()
  await save.click()
  await expect(page.getByText('Carteira de teste', { exact: true })).toBeVisible()
  await expect(page.getByRole('article').filter({ hasText: 'Carteira de teste' })).toContainText('Principal')
  await page.reload()
  await expect(page.getByText('Carteira de teste', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /editar.*Carteira de teste/i }).click()
  await name.fill('Carteira renomeada')
  await save.click()
  await expect(page.getByText('Carteira renomeada', { exact: true })).toBeVisible()
})
